#!/usr/bin/env python3
"""Generates the .resx files and the strongly typed accessor from strings.tsv.

The TSV is the authoring source: key|en|pt. Keeping it in one place
avoids maintaining three parallel lists by hand.
"""
from pathlib import Path
import html

root = Path(__file__).resolve().parents[2]
rows = []
for line in (Path(__file__).parent / "strings.tsv").read_text(encoding="utf-8").splitlines():
    line = line.rstrip("\n")
    if not line.strip() or line.lstrip().startswith("#"):
        continue
    key, en, pt = line.split("|", 2)
    rows.append((key, en, pt))

header = """<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
"""

def resx(values):
    parts = [header]
    for key, value in values:
        parts.append(
            f'  <data name="{key}" xml:space="preserve">\n'
            f"    <value>{html.escape(value, quote=False)}</value>\n"
            f"  </data>\n"
        )
    parts.append("</root>\n")
    return "".join(parts)

resx_dir = root / "src/NotepadMoreOS/Resources"
(resx_dir / "Strings.resx").write_text(resx([(k, en) for k, en, _ in rows]), encoding="utf-8")
(resx_dir / "Strings.pt-BR.resx").write_text(resx([(k, pt) for k, _, pt in rows]), encoding="utf-8")

properties = "".join(
    f"    public static string {key} => Get(nameof({key}));\n" for key, _, _ in rows
)

(resx_dir / "Strings.g.cs").write_text(
    """// <auto-generated>
// Generated from tools/localization/strings.tsv. Do not edit by hand.
// </auto-generated>

using System.Resources;

namespace NotepadMoreOS.Resources;

/// <summary>Strongly typed access to the localized UI strings.</summary>
public static class Strings
{
    private static readonly ResourceManager Manager =
        new("NotepadMoreOS.Resources.Strings", typeof(Strings).Assembly);

    /// <summary>Returns the localized string for a resource key, falling back to the key.</summary>
    public static string Get(string key) => Manager.GetString(key) ?? key;

""" + properties + "}\n",
    encoding="utf-8",
)

print(f"{len(rows)} strings written")
